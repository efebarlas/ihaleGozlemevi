"""Phase-1 plan for backfill-history (M5f): a FIXED, SEEDED sample of bulletin days across the whole history, so the
trend picture can be seen before the day-by-day walk fills everything in.

Rule (fixed before any fetch, never tuned afterwards):
  * seed SEED = 20261123 (the day the rule was written); one `random.Random(SEED)`, drawn in chronological order
  * 2019-01 .. 2026-09: per calendar month one uniformly drawn business day (Mon-Fri) of that month  -> 93 days
  * 2016-01 .. 2018-12: per calendar quarter one uniformly drawn business day of that quarter        -> 12 days
  * all three bulletin types per day (mal, hizmet, yapim) -> 105 days, 315 requests
  * a day on which all three types come back "no bulletin" (holiday) is retried on the next business day, at most 3
    times, at the END of the list (the second pass for the gaps; done by backfill_history, not here)
  * order: interleaved across years, newest year first; round r takes each year's r-th sampled day (newest first
    within the year), so one night already touches many years; types in the order mal, hizmet, yapim
The list is written to <data>/backfill-plan.txt (`python -m ihale backfill-plan --write`), one `YYYY-MM-DD type` per
line. Phase-2 windows are appended to that file and are fetched before the day-by-day walk. No EKAP requests here.
"""
from __future__ import annotations

import random
from datetime import date, timedelta

SEED = 20261123
TYPES = ("mal", "hizmet", "yapim")
MONTHLY_FROM, MONTHLY_TO = (2019, 1), (2026, 9)
QUARTERLY_FROM, QUARTERLY_TO = (2016, 1), (2018, 12)


def _business_days(start: date, end: date) -> list[date]:
    out, d = [], start
    while d <= end:
        if d.weekday() < 5:
            out.append(d)
        d += timedelta(days=1)
    return out


def _month_end(y: int, m: int) -> date:
    return (date(y + (m == 12), m % 12 + 1, 1)) - timedelta(days=1)


def sample_days(seed: int = SEED) -> list[date]:
    """The sampled business days in chronological order (draw order)."""
    rng = random.Random(seed)
    days: list[date] = []
    y, m = QUARTERLY_FROM
    while (y, m) <= QUARTERLY_TO:                       # quarters start at months 1, 4, 7, 10
        days.append(rng.choice(_business_days(date(y, m, 1), _month_end(y, m + 2))))
        m += 3
        if m > 12:
            y, m = y + 1, m - 12
    y, m = MONTHLY_FROM
    while (y, m) <= MONTHLY_TO:
        days.append(rng.choice(_business_days(date(y, m, 1), _month_end(y, m))))
        y, m = (y + 1, 1) if m == 12 else (y, m + 1)
    return sorted(days)


def interleave(days: list[date]) -> list[date]:
    """Round-robin over years (newest year first); inside a year newest day first."""
    by_year: dict[int, list[date]] = {}
    for d in sorted(days, reverse=True):
        by_year.setdefault(d.year, []).append(d)
    years = sorted(by_year, reverse=True)
    out: list[date] = []
    for r in range(max(len(v) for v in by_year.values())):
        out += [by_year[y][r] for y in years if r < len(by_year[y])]
    return out


def generate(seed: int = SEED) -> list[tuple[date, str]]:
    return [(d, t) for d in interleave(sample_days(seed)) for t in TYPES]


def render(seed: int = SEED) -> str:
    targets = generate(seed)
    head = (f"# backfill-history plan, phase 1. Generated by ihale.backfill_plan (seed {seed}); rule in that module.\n"
            f"# {len(targets) // len(TYPES)} days x {len(TYPES)} types = {len(targets)} targets. Append later phases below.\n")
    return head + "".join(f"{d.isoformat()} {t}\n" for d, t in targets)
